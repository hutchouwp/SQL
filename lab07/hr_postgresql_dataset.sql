-- HR sample dataset for PostgreSQL (teaching/labs)
DROP SCHEMA IF EXISTS hr CASCADE;
CREATE SCHEMA hr;
SET search_path = hr;

CREATE TABLE regions (
  region_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_name TEXT NOT NULL
);
CREATE TABLE countries (
  country_id   CHAR(2) PRIMARY KEY,
  country_name TEXT NOT NULL,
  region_id    INTEGER NOT NULL REFERENCES regions(region_id)
);
CREATE TABLE locations (
  location_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  street_address TEXT,
  postal_code    TEXT,
  city           TEXT NOT NULL,
  state_province TEXT,
  country_id     CHAR(2) NOT NULL REFERENCES countries(country_id)
);
CREATE TABLE departments (
  department_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name TEXT NOT NULL,
  manager_id      INTEGER,
  location_id     INTEGER REFERENCES locations(location_id)
);
CREATE TABLE jobs (
  job_id     VARCHAR(10) PRIMARY KEY,
  job_title  TEXT NOT NULL,
  min_salary INTEGER CHECK (min_salary >= 0),
  max_salary INTEGER CHECK (max_salary >= min_salary)
);
CREATE TABLE employees (
  employee_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     TEXT,
  last_name      TEXT NOT NULL,
  email          TEXT NOT NULL UNIQUE,
  phone_number   TEXT,
  hire_date      DATE NOT NULL,
  job_id         VARCHAR(10) NOT NULL REFERENCES jobs(job_id),
  salary         NUMERIC(10,2) NOT NULL CHECK (salary >= 0),
  commission_pct NUMERIC(4,2) CHECK (commission_pct IS NULL OR (commission_pct >= 0 AND commission_pct <= 1)),
  manager_id     INTEGER REFERENCES employees(employee_id),
  department_id  INTEGER REFERENCES departments(department_id)
);
CREATE TABLE job_history (
  employee_id   INTEGER NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
  start_date    DATE NOT NULL,
  end_date      DATE NOT NULL,
  job_id        VARCHAR(10) NOT NULL REFERENCES jobs(job_id),
  department_id INTEGER NOT NULL REFERENCES departments(department_id),
  PRIMARY KEY (employee_id, start_date),
  CHECK (end_date > start_date)
);

